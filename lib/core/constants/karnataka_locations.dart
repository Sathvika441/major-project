  static List<String> get districts => districtsByState[state] ?? [];

  static List<String> districtsFor(String s) =>
      districtsByState[s] ?? districtsByState[state] ?? [];

  static List<String> taluksFor(String district) =>
      taluksByDistrict[district] ?? ['General'];

  static String formatLocation({
    required String state,
    required String district,
    required String taluk,
    required String village,
  }) {
    final parts = <String>[];
    if (village.trim().isNotEmpty) parts.add(village.trim());
    if (taluk.trim().isNotEmpty) parts.add(taluk.trim());
    if (district.trim().isNotEmpty) parts.add(district.trim());
    if (state.trim().isNotEmpty) parts.add(state.trim());
    return parts.join(', ');
  }
